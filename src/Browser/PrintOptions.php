<?php

namespace Daif\ChromePdfBundle\Browser;

use Daif\ChromePdfBundle\Exception\BrowserException;

/**
 * Translates the bundle $pdfOptions contract into Page.printToPDF parameters.
 *
 * @internal
 */
final class PrintOptions
{
    /** Chrome defaults (inches), used when the option is not provided. */
    public const DEFAULT_PAPER_WIDTH = 8.5;
    public const DEFAULT_PAPER_HEIGHT = 11.0;
    public const DEFAULT_MARGIN = 0.4;

    /** CSS pixels per inch. */
    public const PX_PER_INCH = 96;

    private const FLOAT_OPTIONS = ['paperWidth', 'paperHeight', 'marginTop', 'marginBottom', 'marginLeft', 'marginRight', 'scale'];
    private const BOOL_OPTIONS = ['landscape', 'printBackground', 'preferCSSPageSize', 'generateDocumentOutline', 'generateTaggedPdf'];

    /** Template used for the missing header or footer so Chrome does not print its default date/title/URL. */
    public const EMPTY_TEMPLATE = '<span></span>';

    /**
     * @param array<string, mixed> $pdfOptions
     *
     * @return array<string, mixed>
     */
    public static function toCdp(array $pdfOptions): array
    {
        $params = [];

        foreach (self::FLOAT_OPTIONS as $name) {
            if (isset($pdfOptions[$name])) {
                if (!is_numeric($pdfOptions[$name])) {
                    throw new BrowserException(\sprintf('PDF option "%s" must be a number (inches), "%s" given.', $name, get_debug_type($pdfOptions[$name])));
                }
                $params[$name] = (float) $pdfOptions[$name];
            }
        }

        foreach (self::BOOL_OPTIONS as $name) {
            if (isset($pdfOptions[$name])) {
                $params[$name] = (bool) $pdfOptions[$name];
            }
        }

        if (isset($pdfOptions['pageRanges']) && '' !== (string) $pdfOptions['pageRanges']) {
            $params['pageRanges'] = (string) $pdfOptions['pageRanges'];
        }

        $header = isset($pdfOptions['headerTemplate']) ? (string) $pdfOptions['headerTemplate'] : null;
        $footer = isset($pdfOptions['footerTemplate']) ? (string) $pdfOptions['footerTemplate'] : null;
        if (null !== $header || null !== $footer) {
            $params['displayHeaderFooter'] = true;
            $params['headerTemplate'] = $header ?? self::EMPTY_TEMPLATE;
            $params['footerTemplate'] = $footer ?? self::EMPTY_TEMPLATE;
        }

        if (!empty($pdfOptions['singlePage'])) {
            // the page height is computed from the document height, ranges make no sense
            unset($params['pageRanges']);
            // the height is computed, so landscape only means "use the long edge as width"
            if (!empty($params['landscape'])) {
                $params['paperWidth'] = max($params['paperWidth'] ?? self::DEFAULT_PAPER_WIDTH, $params['paperHeight'] ?? self::DEFAULT_PAPER_HEIGHT);
            }
            unset($params['landscape']);
        }

        return $params;
    }

    /**
     * Printable width in CSS pixels, used to lay out the document before measuring it (singlePage).
     *
     * @param array<string, mixed> $params Page.printToPDF parameters
     */
    public static function printableWidthPx(array $params): float
    {
        $paperWidth = (float) ($params['paperWidth'] ?? self::DEFAULT_PAPER_WIDTH);
        $marginLeft = (float) ($params['marginLeft'] ?? self::DEFAULT_MARGIN);
        $marginRight = (float) ($params['marginRight'] ?? self::DEFAULT_MARGIN);
        $scale = (float) ($params['scale'] ?? 1.0);

        return max(1.0, ($paperWidth - $marginLeft - $marginRight) * self::PX_PER_INCH / ($scale > 0 ? $scale : 1.0));
    }

    /**
     * Paper height (inches) fitting a document of $contentHeightPx CSS pixels on one page.
     *
     * @param array<string, mixed> $params Page.printToPDF parameters
     */
    public static function singlePageHeight(array $params, float $contentHeightPx): float
    {
        $marginTop = (float) ($params['marginTop'] ?? self::DEFAULT_MARGIN);
        $marginBottom = (float) ($params['marginBottom'] ?? self::DEFAULT_MARGIN);
        $scale = (float) ($params['scale'] ?? 1.0);

        // +2px of slack against sub-pixel rounding that would push one line to a second page
        return (ceil($contentHeightPx) + 2) * ($scale > 0 ? $scale : 1.0) / self::PX_PER_INCH + $marginTop + $marginBottom;
    }

    /**
     * Counts the pages of a PDF generated by Chrome (root /Pages dictionary /Count).
     */
    public static function countPdfPages(string $pdf): int
    {
        $count = 0;
        if (preg_match_all('#<<((?:(?!>>).)*?/Type\s*/Pages\b(?:(?!>>).)*?)>>#s', $pdf, $matches)) {
            foreach ($matches[1] as $dictionary) {
                if (preg_match('#/Count\s+(\d+)#', $dictionary, $countMatch)) {
                    $count = max($count, (int) $countMatch[1]);
                }
            }
        }

        if (0 === $count) {
            // fallback: count page objects
            $count = (int) preg_match_all('#/Type\s*/Page\b(?!s)#', $pdf);
        }

        return $count;
    }
}
